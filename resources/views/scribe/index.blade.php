        <h1 id="introduction">Introduction</h1>
<p>API documentation for the Equipment Maintenance Tracking System.</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost:8000</code>
</aside>
<p>This documentation provides information about the Equipment Maintenance Tracking System API.</p>
<p>You can explore the available endpoints, view request and response examples, and test API requests using the documentation interface.</p>
<p>Protected endpoints require a valid JWT Bearer Token obtained through the login endpoint.</p>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {YOUR_JWT_TOKEN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Use the JWT access token obtained from the login endpoint. Enter the token in the Bearer Token field to access protected API endpoints.</p>

